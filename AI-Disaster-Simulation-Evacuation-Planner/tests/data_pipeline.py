def run_cli(script, *args):
    return subprocess.run([sys.executable, str(ROOT / "scripts" / script), *args], capture_output=True, text=True, cwd=ROOT)


def test_cli_build_then_validate(fixture_files, tmp_path):
    out = tmp_path / "proc"
    r = run_cli("build_dataset.py", "--name", "cli_test", "--roads", str(fixture_files["roads"]),
                "--population", str(fixture_files["population"]), "--shelters", str(fixture_files["shelters"]),
                "--out-dir", str(out), "--roads-license", "test")
    assert r.returncode == 0, r.stderr
    assert (out / "cli_test.json").is_file() and (out / "cli_test.manifest.json").is_file()
    assert "PLANNER_DATASET=" in r.stdout and "Built 'cli_test'" in r.stdout
    v = run_cli("validate_dataset.py", str(out / "cli_test.json"))
    assert v.returncode == 0 and "OK" in v.stdout and "data kind: real" in v.stdout


