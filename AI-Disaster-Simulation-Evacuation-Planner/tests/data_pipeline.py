def test_roads_import(fixture_files):
    r = read_roads_geojson(fixture_files["roads"])
    assert len(r["nodes"]) == N * N and len(r["edges"]) == 2 * N * (N - 1)             # island dropped
    assert r["stats"]["nodes_dropped_disconnected"] == 2 and r["stats"]["skipped_geometries"] == {"Point": 1}
    assert {e["arterial"] for e in r["edges"]} == {True, False}
    fr = r["frame"]
    assert abs(fr.width_m - (N - 1) * STEP * M_PER_DEG_LAT * fr.cos_lat) < 1 and abs(fr.lat0 - LAT0) < 1e-9
    assert fr.width_m < 2000 and fr.height_m < 2000                                    # the far-away island must not widen it
    assert abs(fr.cos_lat - math.cos(math.radians(LAT0 + (N - 1) * STEP / 2))) < 1e-9   # cos(lat) of the KEPT network
    assert all(0 <= n["x"] <= fr.width_m + 1 and 0 <= n["y"] <= fr.height_m + 1 for n in r["nodes"])


