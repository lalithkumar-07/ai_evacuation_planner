def tiny():
    return {"meta": {"name": "t", "frame": {"lat0": 10.0, "lon0": 20.0, "cos_lat": 0.98, "width_m": 100, "height_m": 100},
                     "provenance": {l: {"source": "synthetic"} for l in ("roads", "population", "shelters")}},
            "nodes": [{"id": i, "x": 10.0 * i, "y": 5.0} for i in range(4)],
            "edges": [{"u": i, "v": i + 1, "distance": 10.0, "arterial": False} for i in range(3)],
            "population": [{"id": 0, "node": 0, "size": 10, "mobility": "vehicle"}],
            "shelters": [{"id": 0, "node": 3, "capacity": 50, "occupancy": 0}]}


def test_valid_tiny_dataset():
    r = validate_dataset(tiny())
    assert r.ok and r.stats["nodes"] == 4 and r.stats["components"] == 1 and r.stats["population"] == 10


@pytest.mark.parametrize("mutate, expect", [
    (lambda d: d["edges"].append({"u": 0, "v": 99, "distance": 5}), "connect two different existing nodes"),
    (lambda d: d["edges"].append({"u": 1, "v": 2, "distance": -3}), "positive"),
    (lambda d: d["nodes"].append({"id": 0, "x": 1, "y": 1}), "duplicate node id"),
    (lambda d: d["shelters"].append({"id": 5, "node": 1, "capacity": 5}), "0, 1, 2"),
    (lambda d: d["shelters"][0].update(capacity=0), "capacity must be > 0"),
    (lambda d: d["shelters"][0].update(occupancy=999), "occupancy exceeds"),
    (lambda d: d["population"][0].update(mobility="boat"), "mobility"),
    (lambda d: d["population"][0].update(node=77), "existing node"),
    (lambda d: d["population"].clear(), "at least one group"),
    (lambda d: d["meta"]["frame"].update(width_m=0), "width_m"),
    (lambda d: d["meta"]["frame"].update(cos_lat=1.5), "cos_lat"),
    (lambda d: d["meta"]["provenance"]["roads"].update(source="guess"), "provenance.roads.source"),
    (lambda d: d.pop("shelters"), "Missing top-level keys"),
])
def test_validation_catches_errors(mutate, expect):
    d = tiny()
    mutate(d)
    r = validate_dataset(d)
    assert not r.ok and any(expect in e for e in r.errors), r.errors


def test_validation_warnings_do_not_block():
    d = tiny()
