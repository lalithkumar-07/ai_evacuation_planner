def test_legacy_frame_matches_the_pre_phase3_formula():
    ext = 6000.0
    for x, y in [(0, 0), (3000, 3000), (6000, 6000), (1234.5, 4321.0)]:
        old = [round(ORIGIN_LAT + (y - ext / 2) / M_PER_DEG_LAT, 6),
               round(ORIGIN_LON + (x - ext / 2) / (M_PER_DEG_LAT * math.cos(math.radians(ORIGIN_LAT))), 6)]
        assert to_latlon(x, y, ext) == old == legacy_frame(ext).to_latlon(x, y)        # number or Frame: identical


def test_frame_round_trip():
    f = Frame(lat0=17.4, lon0=78.45, cos_lat=math.cos(math.radians(17.41)), width_m=1700, height_m=1700)
    x, y = from_latlon(*f.to_latlon(800.0, 1200.0), f)
    assert abs(x - 800) < 0.2 and abs(y - 1200) < 0.2
    assert f.bounds()[0] == f.to_latlon(0, 0)


