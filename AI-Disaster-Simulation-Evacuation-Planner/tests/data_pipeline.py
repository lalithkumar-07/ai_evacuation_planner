def test_simulation_runs_on_the_built_dataset(built):
    ds, _, _ = built
    cfg = replace(ScenarioConfig(), evacuation_radius_m=5000, initial_radius_m=150, max_radius_m=500,
                  spread_speed_mps=0.2, duration_s=3600, n_shelters=3)
    sim = Simulation(cfg, "proposed", dataset=ds)
    sim.run()
    arrived = sum(a.size for a in sim.agents if a.status.value == "AT_SHELTER")
    assert arrived == sum(s.occupancy for s in sim.shelters) - 100                       # 100 were already inside
    assert arrived > 0 and all(s.occupancy <= s.capacity for s in sim.shelters)


def test_api_serves_the_real_format_dataset(real_active):
    ds, _ = real_active
    fr = frame_of(ds)
    south, west = fr.to_latlon(0, 0)
    north, east = fr.to_latlon(fr.width_m, fr.height_m)
    inside = lambda p: south - 1e-5 <= p[0] <= north + 1e-5 and west - 1e-5 <= p[1] <= east + 1e-5
    c = TestClient(app, headers={"X-Session-Id": "pipeline-test-0001"})

    info = c.get("/api/dataset").json()
    assert info["kind"] == "real" and info["name"] == "test_fixture" and info["layers"]["roads"]["license"] == "test"
    meta = c.get("/api/meta").json()
    assert meta["synthetic"] is False and meta["dataset"]["kind"] == "real" and meta["n_shelters_max"] == 3
    assert [round(v, 4) for v in meta["bounds"][0]] == [round(south, 4), round(west, 4)]
    assert inside([meta["defaults"]["center_lat"], meta["defaults"]["center_lon"]])

    r = c.post("/api/disaster/start", json={"duration_s": 1800, "initial_radius_m": 150, "max_radius_m": 500,
                                            "evacuation_radius_m": 5000, "center_lat": south + 0.005,
                                            "center_lon": west + 0.005}).json()
    assert r["layers"]["synthetic"] is False and r["layers"]["dataset"]["kind"] == "real"
    assert all(inside(road["a"]) and inside(road["b"]) for road in r["layers"]["roads"])
    assert all(inside(s["latlon"]) for s in r["state"]["shelters"]) and inside(r["state"]["disaster"]["center"])
    assert len(r["state"]["shelters"]) == 3                                              # dataset has 3 (default asks for 5)
    plan = c.post("/api/evacuation/plan", json={"lat": south + 0.006, "lon": west + 0.012}).json()
    assert inside(plan["origin"]["latlon"]) and plan["proposed"]["path"] and all(inside(p) for p in plan["proposed"]["path"])
    assert c.post("/api/simulation/step", json={"steps": 5}).json()["time_s"] == 150


