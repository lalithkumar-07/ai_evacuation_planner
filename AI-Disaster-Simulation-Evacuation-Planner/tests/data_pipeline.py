def make_fixture(tmp: Path) -> dict:
    """TEST FIXTURE in real formats: roads.geojson, population.csv (UTF-8 BOM, alias headers), shelters.csv."""
    feats = []
    for i in range(N):
        hw = "primary" if i % 3 == 0 else "residential"
        feats.append({"type": "Feature", "properties": {"highway": hw}, "geometry": {"type": "LineString",
                      "coordinates": [[LON0 + j * STEP, LAT0 + i * STEP] for j in range(N)]}})          # east-west
        feats.append({"type": "Feature", "properties": {"highway": hw}, "geometry": {"type": "LineString",
                      "coordinates": [[LON0 + i * STEP, LAT0 + j * STEP] for j in range(N)]}})          # north-south
    feats.append({"type": "Feature", "properties": {"highway": "service"}, "geometry": {"type": "LineString",   # island
                  "coordinates": [[LON0 + 0.05, LAT0 + 0.05], [LON0 + 0.051, LAT0 + 0.05]]}})
    feats.append({"type": "Feature", "properties": {}, "geometry": {"type": "Point", "coordinates": [LON0, LAT0]}})
    (tmp / "roads.geojson").write_text(json.dumps({"type": "FeatureCollection", "features": feats}), encoding="utf-8")

    rows = ["Latitude,Longitude,Population"]
    for i in range(N):
        for j in range(N):
            rows.append(f"{LAT0 + i * STEP + 0.0002:.6f},{LON0 + j * STEP - 0.0002:.6f},{40 + 7 * i + 3 * j}")
    rows += ["abc,78.45,100", "17.40,78.45,", "17.40,78.45,0", "95.0,78.45,50", f"{LAT0 + 0.5:.6f},{LON0:.6f},999"]
    (tmp / "population.csv").write_text("\n".join(rows) + "\n", encoding="utf-8-sig")

    shelters = ["name,lat,lon,capacity,occupancy",
                f"North school,{LAT0 + 5 * STEP:.6f},{LON0 + 2 * STEP:.6f},900,100",
                f"East hall,{LAT0 + 2 * STEP:.6f},{LON0 + 5 * STEP:.6f},700,0",
                f"South gym,{LAT0:.6f},{LON0 + 3 * STEP:.6f},800,0",
                f"Closed,{LAT0 + STEP:.6f},{LON0 + STEP:.6f},0,0",
                f"Far away,{LAT0 + 0.5:.6f},{LON0:.6f},500,0"]
    (tmp / "shelters.csv").write_text("\n".join(shelters) + "\n", encoding="utf-8")
    return {"roads": tmp / "roads.geojson", "population": tmp / "population.csv", "shelters": tmp / "shelters.csv"}


